import { readFileSync } from "node:fs";
import { defineConfig, type Plugin } from "vitepress";
import { MermaidMarkdown } from "vitepress-plugin-mermaid";
import { GROUPS, PAGES, REPO_URL, SITE_DESC } from "../scripts/pages.mjs";

// GitHub Pages deployment: Actions sets GITHUB_REPOSITORY="owner/repo".
// Derive base so one config serves both local preview (base "/") and the
// published project site (base "/repo/"). User-site repos get base "/".
const [owner, repo] = (process.env.GITHUB_REPOSITORY ?? "").split("/");
const onGitHubPages = Boolean(process.env.GITHUB_ACTIONS && owner && repo);
const isUserSite = repo === `${owner}.github.io`;
const base = onGitHubPages ? (isUserSite ? "/" : `/${repo}/`) : "/";

// Absolute origin for canonical/OG URLs: the published GitHub Pages host, or
// the local dev server. SEO tags need absolute URLs; relative ones are ignored
// by crawlers.
const ORIGIN = onGitHubPages ? `https://${owner}.github.io` : "http://localhost:5173";
const SITE_URL = `${ORIGIN}${base}`;
const SITE_NAME = "a2mcp";
// Version and name live in package.json; a literal here would be a second copy
// to forget at release time.
const PKG = JSON.parse(readFileSync(new URL("../../package.json", import.meta.url), "utf8")) as {
	version?: string;
};
const AUTHOR = {
	"@type": "Person",
	name: "adam-ikari",
	url: "https://github.com/adam-ikari",
} as const;
const OG_IMAGE_ALT = "a2mcp：把 omp 的本机工具开成远程 MCP 接口";

// Mermaid settings, handed to the diagram component as a virtual module. This
// replaces withMermaid(), whose Vite plugin injected a *statically imported*
// Mermaid into the app entry — that put mermaid plus every diagram type in the
// entry's import graph, so all of it was fetched on every page including the
// four with no diagram. We keep the plugin's markdown fence (it emits the
// <Mermaid> tag) and register the component ourselves, async, in theme/index.ts.
const mermaidConfig = {
	securityLevel: "loose" as const,
	startOnLoad: false,
	theme: "default",
};

/** Serves `virtual:mermaid-config` for theme/Mermaid.vue. */
function mermaidSettingsPlugin(): Plugin {
	const id = "virtual:mermaid-config";
	const resolved = `\0${id}`;
	return {
		name: "a2mcp-mermaid-settings",
		resolveId: (source) => (source === id ? resolved : undefined),
		load: (source) => (source === resolved ? `export default ${JSON.stringify(mermaidConfig)}` : undefined),
	};
}

// content/ is generated by scripts/sync.mjs from the repo's README_ZN.md,
// CHANGELOG.md and docs/ — never edit files under content/ directly.
// The nav and the sidebar are two readings of the same map (scripts/pages.mjs):
// the nav is the top bar — one entry per group, a group of one becomes a plain
// link — and the sidebar is the full list under the group headings. Neither is
// a second copy of the page list: a page added to the map appears in both.
//
// The order of GROUPS is the site's argument: start here, then use it, then
// know its limits, then integrate against it.
const pagesIn = (group: string) => PAGES.filter((p) => p.group === group);
const navItems = GROUPS.map((group) => {
	const pages = pagesIn(group);
	if (pages.length === 1) return { text: pages[0].nav, link: `/${pages[0].path}` };
	return { text: group, items: pages.map((p) => ({ text: p.nav, link: `/${p.path}` })) };
});

export default defineConfig({
	title: "a2mcp",
	description: SITE_DESC,
	lang: "zh-CN",
	base,

	// Static assets live in website/public (served at base), so the favicon
	// href carries the base prefix; the theme logo is resolved via withBase.
	head: [["link", { rel: "icon", href: `${base}img/favicon.svg` }]],
	srcDir: "content",
	cleanUrls: true,
	// The async Mermaid component above is what actually keeps the diagrams out
	// of the entry's import graph. This is the second line of defence: if some
	// future dependency puts a shared chunk back on the entry graph, keep it out
	// of the render-blocking preload set rather than let it delay first paint.
	shouldPreload: (link) => !link.includes("/chunks/"),
	markdown: {
		// Repo docs are plain CommonMark carrying literal {braces} and
		// <angle-brackets>; VitePress never parses them as JSX, but keep
		// HTML inline so table/list markup in the docs renders.
		html: true,
		// ```mermaid fences become a <Mermaid> component tag. The component
		// itself is registered async in theme/index.ts.
		config: (md) => MermaidMarkdown(md, { class: "mermaid" }),
	},
	// Per-page SEO: canonical, robots, Open Graph, Twitter Card, and JSON-LD.
	// VitePress emits title/description/lang/viewport itself; these are the
	// signals it does not cover. Titles and descriptions come from the
	// frontmatter written by scripts/sync.mjs, one pair per page.
	transformHead({ pageData }) {
		// The 404 page is built through the same hook. It must not claim a
		// canonical URL or invite indexing; the HTTP status already says 404.
		if (pageData.relativePath === "404.md" || pageData.title === "404") {
			return [["meta", { name: "robots", content: "noindex" }]];
		}
		const rel = pageData.relativePath.replace(/index\.md$/, "").replace(/\.md$/, "");
		const url = `${SITE_URL}${rel}`;
		const pageTitle = pageData.title || SITE_NAME;
		const title = pageData.title ? `${pageData.title} | ${SITE_NAME}` : SITE_NAME;
		const desc = pageData.description || SITE_DESC;
		// Social platforms do not render SVG in og:image (Twitter/X, Facebook
		// and Slack all ignore it), so the card ships as a 1200x630 PNG. The
		// editable source is public/img/og.svg next to it.
		const image = `${SITE_URL}img/og.png`;
		const isHome = pageData.relativePath === "index.md";
		const publisher = {
			"@type": "Organization",
			name: SITE_NAME,
			url: SITE_URL,
			logo: { "@type": "ImageObject", url: image },
		};
		const website = {
			"@type": "WebSite",
			name: SITE_NAME,
			alternateName: "pi-a2a-ext",
			description: SITE_DESC,
			url: SITE_URL,
			inLanguage: "zh-CN",
			publisher,
			sameAs: [REPO_URL],
		};
		// A WebSite node on a docs page misdescribes it: only the home page is
		// the site, the rest are articles. The home page also carries the
		// software itself, which is what lets a search engine treat this as a
		// downloadable tool rather than a blog; article pages carry the trail
		// back to the home page.
		const ld = isHome
			? { "@context": "https://schema.org", ...website }
			: {
					"@context": "https://schema.org",
					"@type": "TechArticle",
					headline: pageTitle,
					description: desc,
					url,
					mainEntityOfPage: { "@type": "WebPage", "@id": url },
					image,
					inLanguage: "zh-CN",
					author: AUTHOR,
					publisher,
					isPartOf: website,
				};
		const extra = isHome
			? {
					"@context": "https://schema.org",
					"@type": "SoftwareApplication",
					name: SITE_NAME,
					alternateName: "pi-a2a-ext",
					description: SITE_DESC,
					url,
					applicationCategory: "DeveloperApplication",
					operatingSystem: "Linux, macOS, Windows",
					softwareVersion: PKG.version,
					programmingLanguage: "TypeScript",
					codeRepository: REPO_URL,
					license: `${REPO_URL}/blob/master/LICENSE`,
					author: AUTHOR,
					offers: { "@type": "Offer", price: "0", priceCurrency: "USD" },
					inLanguage: "zh-CN",
				}
			: {
					"@context": "https://schema.org",
					"@type": "BreadcrumbList",
					itemListElement: [
						{ "@type": "ListItem", position: 1, name: "首页", item: SITE_URL },
						{ "@type": "ListItem", position: 2, name: pageTitle, item: url },
					],
				};
		return [
			["link", { rel: "canonical", href: url }],
			// max-image-preview:large is what allows a full-size thumbnail in
			// Google results; the default is a small square. No SearchAction:
			// the local search box has no ?q= URL for a crawler to point at.
			["meta", { name: "robots", content: "index, follow, max-image-preview:large, max-snippet:-1" }],
			["meta", { name: "author", content: "adam-ikari" }],
			["meta", { property: "og:type", content: isHome ? "website" : "article" }],
			["meta", { property: "og:site_name", content: SITE_NAME }],
			["meta", { property: "og:title", content: title }],
			["meta", { property: "og:description", content: desc }],
			["meta", { property: "og:url", content: url }],
			["meta", { property: "og:image", content: image }],
			// Dimensions and type are declared so consumers can lay the card out
			// before the image loads; without them the aspect ratio is unknown.
			["meta", { property: "og:image:type", content: "image/png" }],
			["meta", { property: "og:image:width", content: "1200" }],
			["meta", { property: "og:image:height", content: "630" }],
			["meta", { property: "og:image:alt", content: OG_IMAGE_ALT }],
			["meta", { property: "og:locale", content: "zh_CN" }],
			// summary_large_image, not summary: a 630px-tall card is rendered
			// full-bleed on both timelines, summary would shrink it to a square.
			["meta", { name: "twitter:card", content: "summary_large_image" }],
			["meta", { name: "twitter:title", content: title }],
			["meta", { name: "twitter:description", content: desc }],
			["meta", { name: "twitter:image", content: image }],
			["meta", { name: "twitter:image:alt", content: OG_IMAGE_ALT }],
			// Third tuple element, NOT a key in the attrs object: VitePress renders
			// ["script", attrs, innerHTML] as <script ...>innerHTML</script>. With
			// innerHTML inside attrs it was serialized as an HTML attribute, so the
			// script body was empty and crawlers saw no structured data at all.
			["script", { type: "application/ld+json" }, JSON.stringify(ld)],
			["script", { type: "application/ld+json" }, JSON.stringify(extra)],
		];
	},
	themeConfig: {
		siteTitle: SITE_NAME,
		// A bare string renders alt="" — a decorative image. The logo doubles as
		// the home link, so it needs a name a crawler can read.
		logo: { src: "/img/logo.svg", alt: SITE_NAME },
		// DRAFT=1 ships one holding page (see scripts/sync.mjs). Nav and sidebar go
		// empty with it, so the published site has no way into the docs that are
		// not published. Without the env var both come back verbatim — that way
		// "put the site back" is deleting one line, not reconstructing a config.
		nav: process.env.DRAFT === "1" ? [] : [{ text: "首页", link: "/" }, ...navItems],
		sidebar:
			process.env.DRAFT === "1"
				? {}
				: {
						"/": GROUPS.map((group) => ({
							text: group,
							items: pagesIn(group).map((p) => ({ text: p.nav, link: `/${p.path}` })),
						})),
					},
		socialLinks: [{ icon: "github", link: "https://github.com/adam-ikari/a2mcp" }],
		// The default theme's UI chrome ships in English; a zh-CN site that
		// leaves these alone reads as half-finished (English "Search" box,
		// "Not Found", "Previous page"). VitePress exposes each string.
		sidebarMenuLabel: "目录",
		returnToTopLabel: "回到顶部",
		skipToContentLabel: "跳到正文",
		darkModeSwitchLabel: "外观",
		lightModeSwitchTitle: "切换到亮色模式",
		darkModeSwitchTitle: "切换到暗色模式",
		docFooter: { prev: "上一页", next: "下一页" },
		outline: { label: "本页目录", level: [2, 3] },
		notFound: {
			title: "页面不存在",
			// The default is an English Kerouac quote. State what happened
			// instead of guessing at a cause the server cannot know.
			quote:
				process.env.DRAFT === "1" ? "站点正在重写，没有别的页面。" : "这个地址下没有 .md 文件。站点的页面都列在左侧。",
			linkText: "回到首页",
			linkLabel: "回到首页",
		},
		search: {
			provider: "local",
			options: {
				translations: {
					button: { buttonText: "搜索文档", buttonAriaLabel: "搜索文档" },
					modal: {
						displayDetails: "显示详细列表",
						resetButtonTitle: "清除查询",
						backButtonTitle: "关闭搜索",
						noResultsText: "没有找到结果：",
						footer: {
							selectText: "选择",
							selectKeyAriaLabel: "回车键",
							navigateText: "切换",
							navigateUpKeyAriaLabel: "向上箭头",
							navigateDownKeyAriaLabel: "向下箭头",
							closeText: "关闭",
							closeKeyAriaLabel: "Esc",
						},
					},
				},
			},
		},
		footer: {
			message: "MIT 协议。文档站由仓库文档生成，改动以仓库为准。",
			copyright: `Copyright © 2026 adam-ikari`,
		},
	},
	vite: { plugins: [mermaidSettingsPlugin()] },
});
